/**
 * Get all communes for a specific Wilaya code (1-69)
 * @param {number|string} wilayaCode 
 * @returns {Array<{ name: string, arName: string, postalCode: string }>}
 */
export function getCommunesForWilaya(wilayaCode) {
  const code = parseInt(wilayaCode, 10);
  const list = ALGERIA_COMMUNES[code];
  if (list && list.length > 0) {
    return list;
  }
  // Generic fallback if not specifically listed
  return [
    { name: 'Centre-Ville', arName: 'وسط المدينة', postalCode: `${String(code).padStart(2, '0')}000` }
  ];
}
